def generate_reminder_times(dosage: str):

    dosage = dosage.strip()

    mapping = {
        "1-0-0": ["08:00"],
        "0-1-0": ["14:00"],
        "0-0-1": ["20:00"],

        "1-0-1": ["08:00", "20:00"],
        "1-1-0": ["08:00", "14:00"],
        "0-1-1": ["14:00", "20:00"],

        "1-1-1": ["08:00", "14:00", "20:00"]
    }

    return mapping.get(dosage, [])