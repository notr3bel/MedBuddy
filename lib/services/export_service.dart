import 'package:pdf/pdf.dart';
import 'package:pdf/widgets.dart' as pw;
import 'package:printing/printing.dart';
import 'package:share_plus/share_plus.dart';

class ExportService {
  /// Strips markdown syntax (asterisks, hashtags, blockquotes, links) for clean text export.
  static String cleanMarkdown(String text) {
    if (text.isEmpty) return text;
    String result = text;
    // Remove bold/italic asterisks (*, **, ***)
    result = result.replaceAll(RegExp(r'\*+'), '');
    // Remove headers (#, ##, ###)
    result = result.replaceAll(RegExp(r'^#+\s*', multiLine: true), '');
    // Remove blockquotes (>)
    result = result.replaceAll(RegExp(r'^>\s*', multiLine: true), '');
    // Remove markdown link syntax [text](url) -> text
    result = result.replaceAll(RegExp(r'\[([^\]]+)\]\([^\)]+\)'), r'\1');
    // Remove inline code backticks
    result = result.replaceAll('`', '');
    // Replace multiple empty lines with a single blank line
    result = result.replaceAll(RegExp(r'\n{3,}'), '\n\n');
    return result.trim();
  }

  static Future<void> shareText(String text, {String? subject}) async {
    final cleanedText = cleanMarkdown(text);
    // ignore: deprecated_member_use
    await Share.share(cleanedText, subject: subject);
  }

  static Future<void> generateAndPrintPdf({
    required String title,
    required String content,
  }) async {
    final pdf = pw.Document();
    final List<pw.Widget> pdfContentWidgets =
        _parseContentToPdfWidgets(content);

    pdf.addPage(
      pw.MultiPage(
        pageFormat: PdfPageFormat.a4,
        margin: const pw.EdgeInsets.all(36),
        header: (pw.Context context) {
          return pw.Column(
            crossAxisAlignment: pw.CrossAxisAlignment.start,
            children: [
              pw.Row(
                mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
                children: [
                  pw.Text(
                    'MedIntel AI',
                    style: pw.TextStyle(
                      fontSize: 16,
                      fontWeight: pw.FontWeight.bold,
                      color: PdfColors.teal700,
                    ),
                  ),
                  pw.Text(
                    'Date: ${DateTime.now().toString().split(' ')[0]}',
                    style: const pw.TextStyle(
                        fontSize: 9, color: PdfColors.grey700),
                  ),
                ],
              ),
              pw.SizedBox(height: 4),
              pw.Text(
                title,
                style: pw.TextStyle(
                  fontSize: 20,
                  fontWeight: pw.FontWeight.bold,
                  color: PdfColors.blueGrey900,
                ),
              ),
              pw.SizedBox(height: 6),
              pw.Divider(color: PdfColors.teal200, thickness: 1.5),
              pw.SizedBox(height: 10),
            ],
          );
        },
        footer: (pw.Context context) {
          return pw.Column(
            children: [
              pw.Divider(color: PdfColors.grey300, thickness: 0.5),
              pw.SizedBox(height: 4),
              pw.Row(
                mainAxisAlignment: pw.MainAxisAlignment.spaceBetween,
                children: [
                  pw.Text(
                    'Generated by MedIntel AI | For informational reference only',
                    style: const pw.TextStyle(
                        fontSize: 8, color: PdfColors.grey600),
                  ),
                  pw.Text(
                    'Page ${context.pageNumber} of ${context.pagesCount}',
                    style: const pw.TextStyle(
                        fontSize: 8, color: PdfColors.grey600),
                  ),
                ],
              ),
            ],
          );
        },
        build: (pw.Context context) {
          return pdfContentWidgets;
        },
      ),
    );

    await Printing.layoutPdf(
      onLayout: (PdfPageFormat format) async => pdf.save(),
      name: '${title.replaceAll(' ', '_')}.pdf',
    );
  }

  static List<pw.Widget> _parseContentToPdfWidgets(String text) {
    final List<pw.Widget> widgets = [];
    final lines = text.split('\n');
    int itemIndex = 1;

    for (var line in lines) {
      final trimmed = line.trim();
      if (trimmed.isEmpty) {
        widgets.add(pw.SizedBox(height: 4));
        continue;
      }

      // Check structural patterns before stripping symbols
      final isHeader = trimmed.startsWith('#') ||
          (trimmed.startsWith('**') &&
              (trimmed.endsWith('**') || trimmed.contains('**:'))) ||
          RegExp(r'^(Health Status|Key Findings|Suggestions|Overview|Impression|Schedule|Medicines|Precautions|General Instructions|Disclaimer):?',
                  caseSensitive: false)
              .hasMatch(trimmed);

      final isBullet = trimmed.startsWith('-') ||
          trimmed.startsWith('*') ||
          trimmed.startsWith('•') ||
          RegExp(r'^\d+\.').hasMatch(trimmed);
      final isCallout = trimmed.startsWith('>') ||
          trimmed.toLowerCase().contains('warning:') ||
          trimmed.toLowerCase().contains('caution:');

      // Strip all markdown symbols (*, #, >, `, etc.)
      String cleanLine = cleanMarkdown(trimmed);
      // Strip any non-ASCII characters (bullets/emojis) that cause boxes (☒) in PDF Helvetica font
      cleanLine = cleanLine.replaceAll(RegExp(r'[^\x00-\x7F]+'), '').trim();
      if (cleanLine.isEmpty) continue;

      if (isHeader) {
        itemIndex = 1; // Reset list counter for new header section
        widgets.add(pw.SizedBox(height: 8));
        widgets.add(
          pw.Text(
            cleanLine,
            style: pw.TextStyle(
              fontSize: 13,
              fontWeight: pw.FontWeight.bold,
              color: PdfColors.teal800,
            ),
          ),
        );
        widgets.add(pw.SizedBox(height: 3));
      } else if (isBullet) {
        // Strip bullet marker or existing leading digits if cleanLine starts with one
        final bulletText =
            cleanLine.replaceFirst(RegExp(r'^(\d+\.|\-|•|\*)\s*'), '');
        widgets.add(
          pw.Padding(
            padding: const pw.EdgeInsets.only(left: 8, bottom: 4),
            child: pw.Row(
              crossAxisAlignment: pw.CrossAxisAlignment.start,
              children: [
                pw.SizedBox(
                  width: 20,
                  child: pw.Text(
                    '$itemIndex.',
                    style: pw.TextStyle(
                      fontSize: 10,
                      fontWeight: pw.FontWeight.bold,
                      color: PdfColors.teal700,
                    ),
                  ),
                ),
                pw.Expanded(
                  child: pw.Text(
                    bulletText,
                    style: const pw.TextStyle(
                      fontSize: 10,
                      color: PdfColors.grey900,
                      lineSpacing: 1.2,
                    ),
                  ),
                ),
              ],
            ),
          ),
        );
        itemIndex++;
      } else if (isCallout) {
        widgets.add(
          pw.Container(
            margin: const pw.EdgeInsets.symmetric(vertical: 4),
            padding: const pw.EdgeInsets.all(6),
            decoration: pw.BoxDecoration(
              color: PdfColors.amber50,
              borderRadius: pw.BorderRadius.circular(4),
              border: const pw.Border(
                left: pw.BorderSide(color: PdfColors.amber700, width: 2.5),
              ),
            ),
            child: pw.Text(
              cleanLine,
              style: pw.TextStyle(
                fontSize: 9.5,
                fontWeight: pw.FontWeight.bold,
                color: PdfColors.amber900,
              ),
            ),
          ),
        );
      } else {
        widgets.add(
          pw.Padding(
            padding: const pw.EdgeInsets.only(bottom: 3),
            child: pw.Text(
              cleanLine,
              style: const pw.TextStyle(
                fontSize: 10,
                color: PdfColors.grey900,
                lineSpacing: 1.2,
              ),
            ),
          ),
        );
      }
    }

    return widgets;
  }
}
